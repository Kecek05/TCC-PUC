"""Card art v2 renderer.   python Art/CardArt/render.py [--out <folder>]

Turns the pixel-free shapes in shapes.py into every sprite Unity imports for a card:

  towers   Assets/Sprites/Towers/<Name>/<Name>Tower1|2|3.png   white face over its hard black shadow
           ...Tower1_NO_SHADOW.png                             the level 1 face alone
  troops   Assets/Sprites/Enemies/<Name>.png                   the lane body inside its black line
           ...<Name>_NO_OUTLINE.png                            the lane body alone
           ...<Name>_Card.png                                  the card emblem, where a card shows a group
  waves    Assets/Sprites/Enemies/BaseEnemy*.png               the hand-drawn wave enemies, re-inked at that line
  spells   Assets/Sprites/UI/Cards/<icon>.png                  the Codex emblem, white, alpha = brightness
           ...<icon>_card.png                                  the same over a hard shadow, for the card
  sources  Art/Vector/**.svg                                   editable, one file per card

Every file is written under the name the game already imports, so the .meta beside it (pixels per unit, mesh
type, guid) is untouched and no prefab or card asset has to be re-pointed. Art is authored WHITE and tinted in
Unity (CardDataSO.CardColor, SpriteRenderer.color); the black shadow and line stay black under any tint.

Needs: pip install pillow numpy shapely.
"""
import argparse
import os

import numpy as np
from PIL import Image, ImageChops, ImageDraw

import shapes as S

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(os.path.dirname(HERE))

SS = 4                      # supersampling for the vector art
TROOP_SIDE = 496.0          # a troop's silhouette, longest side, on the 748 canvas (BaseEnemy1's measure)
TROOP_LINE = 34.0           # the black line around every body, in px at 2000 pixels per unit
SPELL_SIZE = 512
SPELL_CARD_SCALE = 0.9      # the emblem on a card is drawn a little smaller, to leave its shadow room
SPELL_SHADOW = (16.0, 24.0)

# The four oldest towers and Dart keep the file names they were drawn under.
NO_SHADOW_NAME = {"Dart": "DartTower1_NO_SHADOWS.png"}

SPELL_FILES = {
    "fireball": "meteorite", "lance": "lance", "ice": "snowflakes", "haste": "attackspeed",
    "rage": "rage_icon", "rift": "rift", "ferrugem": "ferrugem",
}
WAVE_ENEMIES = ["BaseEnemy1", "BaseEnemy1_Fast", "BaseEnemy1_Tank", "BaseEnemy2_Normal", "BaseEnemyBoss"]


# ---------------------------------------------------------------- raster helpers

def mask(geom, size, scale, ox, oy):
    """Coverage mask (L) of a geometry: `scale` px per design unit, design origin at (ox, oy) px."""
    big = size * SS
    im = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(im)
    for p in S.polys(geom):
        d.polygon([((ox + x * scale) * SS, (oy + y * scale) * SS) for x, y in p.exterior.coords], fill=255)
        for hole in p.interiors:
            d.polygon([((ox + x * scale) * SS, (oy + y * scale) * SS) for x, y in hole.coords], fill=0)
    return im.reduce(SS)


def layer(alpha, value):
    v = Image.new("L", alpha.size, value)
    return Image.merge("RGBA", (v, v, v, alpha))


def over(*layers):
    out = Image.new("RGBA", layers[0].size, (0, 0, 0, 0))
    for l in layers:
        out = Image.alpha_composite(out, l)
    return out


def shifted(alpha, dx, dy):
    """A mask moved by a whole number of pixels, nothing wrapping round the edge."""
    out = Image.new("L", alpha.size, 0)
    out.paste(alpha, (int(round(dx)), int(round(dy))))
    return out


def save(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


# ---------------------------------------------------------------- towers

def render_towers(out):
    n = 0
    for name, _token, _tint, _family, build in S.TOWERS:
        levels = build()
        folder = os.path.join(out, "Sprites", "Towers", name)
        for i, geom in enumerate(levels):
            face = mask(geom, S.CANVAS, S.U2PX, S.CANVAS / 2, S.CANVAS / 2)
            e = S.SHADOW_EASE[i]
            shadow = shifted(face, S.SHADOW[0] * e, S.SHADOW[1] * e)
            save(over(layer(shadow, 0), layer(face, 255)), os.path.join(folder, f"{name}Tower{i + 1}.png"))
            n += 1
            if i == 0:
                save(layer(face, 255), os.path.join(folder, NO_SHADOW_NAME.get(name, f"{name}Tower1_NO_SHADOW.png")))
                n += 1
        write_tower_svg(name, levels)
    return n


def write_tower_svg(name, levels):
    c = S.CANVAS
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{c}" height="{c}" viewBox="0 0 {c} {c}">',
             f'  <title>{name}</title>',
             '  <desc>Three level sprites on one canvas and one pivot, as the tower prefab stacks them. '
             'Authored white; the game tints them. Generated by Art/CardArt/render.py.</desc>']
    for i, geom in enumerate(levels):
        d = S.path_d(geom, S.U2PX, c / 2, c / 2)
        parts.append(f'  <g id="level{i + 1}"><path d="{d}" fill="#FFFFFF" fill-rule="evenodd"/></g>')
    parts.append('</svg>')
    path = os.path.join(HERE, "..", "Vector", "Towers", f"{name}.svg")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")


# ---------------------------------------------------------------- troops

def troop_fit(geom, side):
    """Bbox-centred on the canvas, the silhouette's longest side `side` px."""
    minx, miny, maxx, maxy = geom.bounds
    s = side / max(maxx - minx, maxy - miny)
    return s, S.CANVAS / 2 - (minx + maxx) / 2 * s, S.CANVAS / 2 - (miny + maxy) / 2 * s


def troop_images(geom, side):
    s, ox, oy = troop_fit(geom, side)
    body = mask(geom, S.CANVAS, s, ox, oy)
    line = mask(geom.buffer(TROOP_LINE / s, join_style=1, quad_segs=24), S.CANVAS, s, ox, oy)
    return over(layer(line, 0), layer(body, 255)), layer(body, 255), (s, ox, oy)


def render_troops(out):
    n = 0
    folder = os.path.join(out, "Sprites", "Enemies")
    for name, _tint, card, lane, lane_size in S.TROOPS:
        emblem = card()
        body = lane() if lane else emblem
        inked, bare, fit = troop_images(body, TROOP_SIDE * lane_size)
        save(inked, os.path.join(folder, f"{name}.png"))
        save(bare, os.path.join(folder, f"{name}_NO_OUTLINE.png"))
        n += 2
        write_troop_svg(name, body, fit)
        if lane:
            inked, _bare, fit = troop_images(emblem, TROOP_SIDE)
            save(inked, os.path.join(folder, f"{name}_Card.png"))
            n += 1
            write_troop_svg(f"{name}_Card", emblem, fit)
    return n


def write_troop_svg(name, geom, fit):
    s, ox, oy = fit
    c = S.CANVAS
    line = S.path_d(geom.buffer(TROOP_LINE / s, join_style=1, quad_segs=24), s, ox, oy)
    body = S.path_d(geom, s, ox, oy)
    text = "\n".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{c}" height="{c}" viewBox="0 0 {c} {c}">',
        f'  <title>{name}</title>',
        '  <desc>A white body inside one black line. Authored white; the game tints it. '
        'Generated by Art/CardArt/render.py.</desc>',
        f'  <path id="line" d="{line}" fill="#000000" fill-rule="evenodd"/>',
        f'  <path id="body" d="{body}" fill="#FFFFFF" fill-rule="evenodd"/>',
        '</svg>']) + "\n"
    path = os.path.join(HERE, "..", "Vector", "Enemies", f"{name}.svg")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


# ---------------------------------------------------------------- wave enemies: the same line, their own shapes

def distance_to(white):
    """Euclidean distance (px) from every pixel to the nearest True pixel. Exact enough within TROOP_LINE + 2."""
    h, w = white.shape
    big = 1e9
    reach = int(TROOP_LINE) + 3
    # 1D distance along each row, then the lower envelope over the rows within reach.
    idx = np.arange(w)
    left = np.where(white, idx, -10 ** 6)
    left = np.maximum.accumulate(left, axis=1)
    right = np.where(white, idx, 10 ** 6)
    right = np.minimum.accumulate(right[:, ::-1], axis=1)[:, ::-1]
    row = np.minimum(idx - left, right - idx).astype(np.float64)
    row = np.minimum(row, big)
    best = np.full((h, w), big)
    for dy in range(-reach, reach + 1):
        src = np.full((h, w), big)
        if dy >= 0:
            src[dy:, :] = row[:h - dy, :]
        else:
            src[:h + dy, :] = row[-dy:, :]
        np.minimum(best, src * src + dy * dy, out=best)
    return np.sqrt(best)


def reink(path_in, path_out):
    """Keeps a hand-drawn enemy's white silhouette exactly and redraws the black line round it at TROOP_LINE."""
    src = np.asarray(Image.open(path_in).convert("RGBA")).astype(np.float64)
    lum = src[:, :, 0] / 255.0
    alpha = src[:, :, 3] / 255.0
    white = lum * alpha                                    # how much of the pixel is body
    d = distance_to(white > 0.5)
    line = np.clip(TROOP_LINE + 0.5 - d, 0.0, 1.0)         # one pixel of antialiasing on the new contour
    out_alpha = np.maximum(line, white)
    out = np.zeros_like(src)
    grey = np.where(out_alpha > 0, white / np.maximum(out_alpha, 1e-6), 0.0)
    out[:, :, 0] = out[:, :, 1] = out[:, :, 2] = np.clip(grey, 0, 1) * 255.0
    out[:, :, 3] = out_alpha * 255.0
    edge = max(out_alpha[0].max(), out_alpha[-1].max(), out_alpha[:, 0].max(), out_alpha[:, -1].max())
    if edge > 0.02:
        print(f"  ! {os.path.basename(path_in)}: the new line touches the edge of the canvas")
    save(Image.fromarray(np.round(out).astype(np.uint8), "RGBA"), path_out)


def render_waves(out, originals):
    n = 0
    for name in WAVE_ENEMIES:
        src = os.path.join(originals, f"{name}.png")
        if not os.path.exists(src):
            print(f"  ! missing original {src}")
            continue
        reink(src, os.path.join(out, "Sprites", "Enemies", f"{name}.png"))
        n += 1
    return n


# ---------------------------------------------------------------- spells

def spell_alpha(raw_path):
    rgb = Image.open(raw_path).convert("RGB")
    r, g, b = rgb.split()
    lum = ImageChops.lighter(ImageChops.lighter(r, g), b)
    alpha = lum.point(lambda v: 0 if v < 14 else min(255, int((v - 14) * 255 / 228)))
    box = alpha.point(lambda v: 255 if v > 8 else 0).getbbox()
    half = max(box[2] - box[0], box[3] - box[1]) / 2 * 1.04
    cx, cy = (box[0] + box[2]) / 2, (box[1] + box[3]) / 2
    return alpha.crop((int(cx - half), int(cy - half), int(cx + half), int(cy + half)))


def render_spells(out):
    n = 0
    folder = os.path.join(out, "Sprites", "UI", "Cards")
    for spell, file in SPELL_FILES.items():
        alpha = spell_alpha(os.path.join(HERE, "spells", "raw", f"spell_{spell}.png"))
        plain = alpha.resize((SPELL_SIZE, SPELL_SIZE), Image.LANCZOS)
        save(layer(plain, 255), os.path.join(folder, f"{file}.png"))

        side = int(round(SPELL_SIZE * SPELL_CARD_SCALE))
        small = Image.new("L", (SPELL_SIZE, SPELL_SIZE), 0)
        small.paste(alpha.resize((side, side), Image.LANCZOS), ((SPELL_SIZE - side) // 2, (SPELL_SIZE - side) // 2))
        shadow = shifted(small, *SPELL_SHADOW)
        save(over(layer(shadow, 0), layer(small, 255)), os.path.join(folder, f"{file}_card.png"))
        n += 2
    return n


# ---------------------------------------------------------------- run

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(PROJECT, "Assets"),
                    help="where the Sprites/ tree is written (default: the project's Assets folder)")
    ap.add_argument("--originals", default=os.path.join(HERE, "wave-originals"),
                    help="the hand-drawn wave enemies as they were before the re-ink")
    args = ap.parse_args()

    print("towers", render_towers(args.out))
    print("troops", render_troops(args.out))
    print("waves ", render_waves(args.out, args.originals))
    print("spells", render_spells(args.out))
